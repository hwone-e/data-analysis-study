str[8:-6] # 기본적으로 슬라이싱이 왼쪽에서 오른쪽으로 가기 때문에, 이렇게 시작 인덱스가 더 오른쪽에 있는 경우 출력을 못함.
str[8:-6:-1] # 이렇게 간격을 -1로 설정해주면, 오른쪽에서 왼쪽으로 역순으로 출력할 수 있음.

