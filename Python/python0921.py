# 문자열 서식 -> 이건 잘 안쓰고 실제로는 문자열 포매팅을 더 많이 쓴다고 함.
name=input("이름을 입력하시오: ")
print('당신의 이름은 %s입니다.' % name) # 이런식으로 문자열 내 문자열을 대입할 수 있음. %s는 문자열
yourname=str(input('성과 이름을 붙여서 입력해주세요. >'))
print('당신의 성은 %s이고, 당신의 이름은 %s입니다.' % (yourname[:-2],yourname[-2:]))
# 이런식으로도 응용이 가능함. %(,)로 앞에 %s가 두개가 있으면, 뒤도 값이 두개

age=int(input("나이를 입력하시오: "))
print('당신의 나이는 %d살 입니다' % age) # 문자열 내 숫자 대입. %d는 정수

print('%s님의 나이는 %d살 입니다.' % (name,age))
