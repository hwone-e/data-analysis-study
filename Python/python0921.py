print('"it\'s ok"') # \'를 해서 "와 '를 모두 출력 가능
print("it's ok\b") # \b는 백슬래시를 하라는 뜻임. 여기서는 k가 지워져서 출력됨
print("it's \no\n\nk") # \n은 줄바꿈. Enter이라고 생각.
print("it's o\tk") # \t는 tap키를 했다고 생각.
# \+Enter을 하면 다음줄까지 이어서 읽으라는 의미. 코드가 길게 이어지면 다음줄로 이어서 씀

